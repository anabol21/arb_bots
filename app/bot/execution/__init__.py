"""Pure execution v2 domain layer.

No sockets, secrets, production writes, systemd or live broker access.
EV2-03 adds a non-owning same-loop transport kernel; importing it does not
connect sockets or place orders.
EV2-04 adds private event adapters; importing them performs no I/O.
EV2-05 adds the WAL/projector/exporter kernel; importing it does not open
files, start threads/tasks, read env, or initialize Sentry.
EV2-06 adds the execution engine and risk gate; importing it does not
acquire locks, open sockets, drain the WAL, or place orders.
EV2-07 adds recovery/restart orchestration; importing it does not
open sockets, drain the WAL, or place orders.
EV2-08 adds the Gear 2.2 strategy bridge; importing it does not
submit intents, write journals, initialize Sentry, or place orders.
EV2-09A adds the local shadow parity/latency harness; importing it
does not connect venues, submit intents, start tasks, or place orders.
"""

